/** DOM contrast regression and real media component flows, local-only fixture. */
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { contrast } from '../../design/refonte-swiftui/packages/tokens/index.mjs';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const require = createRequire(join(root, 'package.json'));
const { chromium } = require('playwright');
const out = join(root, 'docs/refonte-ui/captures/mediatheque');
await mkdir(out, { recursive: true });
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce', serviceWorkers: 'block' });
const blocked = [], errors = [], results = { kit: [], checks: [], shots: [] };
await context.route('**/*', route => {
  const url = new URL(route.request().url());
  if (['http://127.0.0.1:4173', 'http://127.0.0.1:4178'].includes(url.origin)) return route.continue();
  blocked.push(url.href); return route.abort();
});
const page = await context.newPage();
page.on('pageerror', error => errors.push(error.message));
page.setDefaultTimeout(15000);
const shot = async name => { await page.screenshot({ path: join(out, name), fullPage: false }); results.shots.push(name); };
const rgbHex = css => '#' + css.match(/\d+/g).slice(0, 3).map(n => Number(n).toString(16).padStart(2, '0')).join('');
try {
  await page.goto('http://127.0.0.1:4173/');
  for (const mode of ['light', 'dark']) {
    if (mode === 'dark') await page.getByRole('button', { name: 'Passer au thème sombre', exact: true }).click();
    const primary = page.getByRole('button', { name: 'Carte', exact: true });
    const css = await primary.evaluate(element => { const s = getComputedStyle(element); return { color: s.color, background: s.backgroundColor, onAccent: s.getPropertyValue('--sm-on-accent').trim() }; });
    assert.equal(rgbHex(css.color), css.onAccent);
    const ratio = contrast(rgbHex(css.color), rgbHex(css.background));
    assert.ok(ratio >= 4.5, `${mode}: ${ratio}`);
    results.kit.push({ mode, ...css, ratio });
    await shot(`kit-primaire-${mode}.png`);
  }
  await page.goto('http://127.0.0.1:4178/');
  const evidence = async () => JSON.parse(await page.locator('#evidence').textContent());
  const waitEvidence = async (key, value) => page.waitForFunction(({ key, value }) => {
    const text = document.getElementById('evidence')?.textContent;
    if (!text) return false;
    const e = JSON.parse(text);
    return (Array.isArray(e[key]) ? e[key].length : e[key]) === value;
  }, { key, value });
  await page.getByRole('button', { name: 'Vérifier les 41 PNG', exact: true }).click();
  await waitEvidence('renders', 41);
  assert.deepEqual((await evidence()).errors, []);
  results.checks.push('41 actual PNG 1600x1100, accepted by planifierDepot and unchanged by reduirePourEnvoi');
  const showIllustrations = async () => {
    const details = page.locator('details').filter({ has: page.locator('summary').filter({ hasText: 'Illustrations Snack Manager' }) });
    if (await details.getAttribute('open') === null) await details.locator('summary').click();
  };
  const openProduct = async () => { await page.getByRole('button', { name: /^Médiathèque/ }).click(); await showIllustrations(); };
  const add = async (search, label, attempts) => {
    await page.getByRole('searchbox', { name: 'Rechercher une illustration' }).fill(search);
    await page.getByRole('button', { name: "Ajouter l'illustration " + label, exact: true }).click();
    await waitEvidence('attempts', attempts);
    await page.getByRole('button', { name: "Ajouter l'illustration " + label, exact: true }).waitFor({ state: 'visible' });
    await page.waitForFunction(() => !Array.from(document.querySelectorAll('button')).some(b => b.textContent.includes('Ajout…')));
  };
  const close = async () => page.getByRole('button', { name: 'Fermer', exact: true }).click();
  await openProduct();
  assert.equal(await page.getByRole('region', { name: 'Illustrations disponibles' }).getByRole('button').count(), 41);
  await shot('bibliotheque-1440.png');
  await page.setViewportSize({ width: 390, height: 844 });
  await shot('bibliotheque-390.png');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await add('samoussa', 'Samoussa', 1);
  assert.deepEqual((await evidence()).photos, ['existing-original', 'local-media-1']);
  await shot('samoussa-import-attache.png');
  await add('samoussa', 'Samoussa', 2);
  const dedup = await evidence();
  assert.equal(dedup.attempts[0].empreinte, dedup.attempts[1].empreinte);
  assert.equal(dedup.attempts[1].result, 'deduplicated');
  assert.equal(dedup.updates.length, 1);
  await add('brownie', 'Brownie', 3);
  await add('cookie', 'Cookie', 4);
  assert.deepEqual((await evidence()).photos, ['existing-original', 'local-media-1', 'local-media-2']);
  await page.getByRole('status').filter({ hasText: /Elle rejoint votre médiathèque — ce plat porte déjà 3 photos/ }).waitFor();
  results.checks.push('product upload calls existing deposer, preserves first reference, deduplicates identical PNG, max 3 attachments retained');
  await close();
  await page.getByRole('checkbox', { name: 'Refuser le quota' }).check();
  await openProduct();
  await add('cola', 'Canette cola', 5);
  await page.getByRole('alert').filter({ hasText: 'Médiathèque pleine' }).waitFor();
  assert.equal((await evidence()).attempts[4].result, 'quota-refused');
  await shot('quota-refuse.png');
  await close();
  await page.getByRole('checkbox', { name: 'Refuser le quota' }).uncheck();
  await page.getByRole('checkbox', { name: 'Raster lent (5 secondes)' }).check();
  await openProduct();
  await page.getByRole('searchbox', { name: 'Rechercher une illustration' }).fill('cola');
  await page.getByRole('button', { name: "Ajouter l'illustration Canette cola", exact: true }).click();
  await waitEvidence('pending', 1);
  assert.equal(await page.getByRole('button', { name: "Ajouter l'illustration Canette cola", exact: true }).isDisabled(), true);
  await close();
  await waitEvidence('pending', 0);
  assert.equal((await evidence()).attempts.length, 5);
  results.checks.push('quota refusal visible; closing during native canvas toBlob preparation prevents upload callback');
  await page.getByRole('checkbox', { name: 'Raster lent (5 secondes)' }).uncheck();
  await page.getByRole('button', { name: 'Ouvrir le choix de marque' }).click();
  await showIllustrations();
  await add('pizza végét', 'Pizza végétarienne', 6);
  assert.deepEqual((await evidence()).updates.at(-1), { kind: 'brand', id: 'local-media-4' });
  await page.getByRole('button', { name: /illustration-pizza-vegetarian.png/ }).waitFor();
  assert.equal(await page.getByRole('button', { name: /illustration-pizza-vegetarian.png/ }).getAttribute('aria-pressed'), 'true');
  await shot('choix-marque.png');
  await close();
  await page.getByRole('checkbox', { name: 'Retirer le droit d’action' }).check();
  await page.getByRole('button', { name: 'Ouvrir le choix de marque' }).click();
  await showIllustrations();
  await page.getByRole('searchbox', { name: 'Rechercher une illustration' }).fill('cola');
  await page.getByRole('button', { name: "Ajouter l'illustration Canette cola", exact: true }).click();
  await close();
  assert.equal((await evidence()).attempts.length, 6);
  results.checks.push('brand upload invokes existing onChoisir and selected state; canAct=false prevents upload');
  results.evidence = await evidence();
  assert.deepEqual(errors, []);
  assert.deepEqual(blocked, []);
  results.pass = true;
} catch (error) {
  results.pass = false;
  results.error = String(error);
  await shot('failure.png');
  throw error;
} finally {
  await writeFile(join(out, 'resultats-browser.json'), JSON.stringify({ ...results, errors, blocked }, null, 2));
  await browser.close();
}
console.log(JSON.stringify({ pass: results.pass, checks: results.checks, kit: results.kit, out }, null, 2));
